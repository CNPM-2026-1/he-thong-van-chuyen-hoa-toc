);
GO

-- 16. SuCo
CREATE TABLE SuCo (
    MaSuCo UNIQUEIDENTIFIER NOT NULL,
    MaDonHang UNIQUEIDENTIFIER NULL,
    MaChuyenXe UNIQUEIDENTIFIER NULL,
    NguoiBaoCao UNIQUEIDENTIFIER NULL,
