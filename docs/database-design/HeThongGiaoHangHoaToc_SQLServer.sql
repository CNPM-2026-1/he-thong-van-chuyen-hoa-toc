);
GO

-- 15. GiaoDichCOD
CREATE TABLE GiaoDichCOD (
    MaGiaoDich UNIQUEIDENTIFIER NOT NULL,
    MaDonHang UNIQUEIDENTIFIER NOT NULL,
    MaTaiXeThu UNIQUEIDENTIFIER NULL,
    MaTaiKhoanNhan UNIQUEIDENTIFIER NULL,
